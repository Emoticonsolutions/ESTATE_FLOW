// Helper to generate units for Tower A
export function generateUnitsForTower(towerId: string, projectId: string, companyId: string): Unit[] {
  const units: Unit[] = [];
  const floors = [1, 2, 3, 4, 5, 6];
  const unitSuffixes = ['01', '02', '03', '04'];

  const sampleStatuses: { [key: string]: Unit['status'] } = {
    '101': 'Sold',
    '102': 'Booked',
    '103': 'Available',
    '104': 'Available',
    '201': 'Booked',
    '202': 'Available',
    '203': 'Blocked',
    '204': 'Available',
    '301': 'Available',
    '302': 'Reserved',
    '303': 'Available',
    '304': 'Booked',
    '401': 'On Hold',
    '402': 'Available',
    '403': 'Available',
    '404': 'Booked',
    '501': 'Available',
    '502': 'Blocked',
    '503': 'Available',
    '504': 'Sold',
    '601': 'Booked',
    '602': 'Available',
    '603': 'Available',
    '604': 'Available',
  };

  floors.forEach((floor) => {
    unitSuffixes.forEach((suffix, idx) => {
      const uNum = `${floor}${suffix}`;
      const is3BHK = idx % 2 === 0;
      const carpet = is3BHK ? 1420 : 1080;
      const superBuilt = is3BHK ? 1860 : 1440;
      const base = is3BHK ? 14500000 : 11200000;
      const status = sampleStatuses[uNum] || 'Available';

      units.push({
        id: `unit-${towerId}-${uNum}`,
        companyId,
        projectId,
        towerId,
        floorNumber: floor,
        unitNumber: uNum,
        unitType: is3BHK ? '3 BHK' : '2 BHK',
        bhk: is3BHK ? '3 BHK' : '2 BHK',
        carpetArea: carpet,
        builtUpArea: Math.round(carpet * 1.2),
        superBuiltUpArea: superBuilt,
        balconyArea: is3BHK ? 120 : 85,
        facing: idx === 0 ? 'East' : idx === 1 ? 'North' : idx === 2 ? 'North-East' : 'West',
        basePrice: base,
        floorRiseRate: floor * 50000,
        plcRate: idx === 0 || idx === 1 ? 250000 : 100000,
        parkingCharges: 350000,
        clubhouseCharges: 250000,
        maintenanceCharges: 120000,
        status,
        customerName: status === 'Booked' || status === 'Sold' ? 'Dr. Arvind Swaminathan' : undefined,
        blockedUntil: status === 'Blocked' ? '2026-11-06T18:00:00' : undefined,
        blockedBy: status === 'Blocked' ? 'Rohan Sharma (Sales Exec)' : undefined,
      });
    });
  });

  return units;
}

